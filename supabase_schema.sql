create extension if not exists pgcrypto;

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    nome text not null,
    email text not null,
    ativo boolean not null default true,
    role text not null default 'user' check (role in ('user','admin')),
    criado_em timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, nome, email)
    values (
        new.id,
        coalesce(nullif(new.raw_user_meta_data->>'nome',''), split_part(new.email,'@',1)),
        lower(new.email)
    )
    on conflict (id) do update set
        email = excluded.email;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
    select exists (
        select 1 from public.profiles
        where id = auth.uid() and role = 'admin' and ativo = true
    );
$$;

create table if not exists public.tipos_equipamentos (
    id bigint generated by default as identity primary key,
    nome text not null unique,
    descricao text,
    ativo boolean not null default true
);

create table if not exists public.equipamentos (
    id bigint generated by default as identity primary key,
    tipo_id bigint not null references public.tipos_equipamentos(id),
    nome text not null,
    patrimonio text unique,
    modelo text,
    fabricante text,
    placa text,
    ano integer,
    horimetro numeric(10,2) not null default 0,
    status text not null default 'ATIVO' check (status in ('ATIVO','MANUTENCAO','INATIVO')),
    observacoes text,
    ativo boolean not null default true,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now()
);

create or replace function public.atualizar_equipamento_timestamp()
returns trigger
language plpgsql
as $$
begin
    new.atualizado_em = now();
    return new;
end;
$$;

drop trigger if exists equipamentos_updated_at on public.equipamentos;
create trigger equipamentos_updated_at
before update on public.equipamentos
for each row execute procedure public.atualizar_equipamento_timestamp();

create table if not exists public.itens_inspecao (
    id bigint generated by default as identity primary key,
    tipo_id bigint not null references public.tipos_equipamentos(id),
    nome text not null,
    descricao text,
    categoria text not null default 'Geral',
    ordem integer not null default 0,
    obrigatorio boolean not null default true,
    ativo boolean not null default true
);

create table if not exists public.checklists (
    id bigint generated by default as identity primary key,
    equipamento_id bigint not null references public.equipamentos(id),
    usuario_id uuid not null references public.profiles(id),
    horimetro numeric(10,2) not null default 0,
    status text not null check (status in ('APROVADO','APROVADO_COM_OBSERVACAO','REPROVADO')),
    observacoes text,
    realizado_em timestamptz not null default now()
);

create table if not exists public.respostas_checklist (
    id bigint generated by default as identity primary key,
    checklist_id bigint not null references public.checklists(id) on delete cascade,
    item_inspecao_id bigint not null references public.itens_inspecao(id),
    status text not null check (status in ('OK','ATENCAO','PROBLEMA','NAO_APLICAVEL')),
    observacao text,
    foto_nome text,
    foto_path text,
    respondido_em timestamptz not null default now(),
    unique (checklist_id, item_inspecao_id)
);

